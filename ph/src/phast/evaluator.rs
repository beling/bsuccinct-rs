impl BucketEvaluator for Weights {
    type Value = i64;

    const MIN: Self::Value = i64::MIN;

    fn eval(&self, bucket_nr: usize, bucket_size: usize) -> Self::Value {
        let sw = self.0.get(bucket_size-1).copied()
            .unwrap_or_else(|| {
                let len = self.0.len();
                let l = self.0[len-1];
                let p = self.0[len-2];
                l + (l-p) * (bucket_size - len) as i32
            }) as i64;
        // The weights are scaled by 4 (see `internal/phast/scale_weights.py`),
        // so the penalty for the bucket number is scaled the same way: 4 * 1024.
        sw - 4096 * bucket_nr as i64
    }
}